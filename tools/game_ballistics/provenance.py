def close(a, b, tolerance=1e-3):
    """Numbers equal within `tolerance` (relative, at least `tolerance` absolute), the rule of gamecheck.py."""
    return abs(a - b) <= max(tolerance, abs(b) * tolerance)


def num(x):
    """A number for a table cell."""
    if x is None:
        return "-"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, float)):
        return f"{x:.6g}"
    return str(x)


class Data:
    """Everything the tables are made from."""

    def __init__(self, resolved_path, sb_dir, sc_dir, dump_dir):
        self.sc_dir = sc_dir
        self.resolved = {k.replace("/Game/", "", 1): v for k, v in json.load(open(resolved_path)).items()}
        self.by_base = collections.defaultdict(list)
        for key in self.resolved:
            self.by_base[key.rsplit("/", 1)[-1]].append(key)
        raw = json.load(open(os.path.join(sb_dir, "weapons.json"), encoding="utf-8"))
        self.sb = {k: v for k, v in raw.items() if not k.startswith("_")}
        snap = json.load(open(os.path.join(sb_dir, "tests", "data", "game_weapons.json"), encoding="utf-8"))
        self.snap = {k: v for k, v in snap.items() if not k.startswith("_")}
        node = subprocess.run(["node", "--import", os.path.join(DIRECT_FIRE, "register.mjs"), os.path.join(DIRECT_FIRE, "weapons_json.mjs"), sc_dir],
                              check=True, capture_output=True, text=True)
        self.sc = json.loads(node.stdout)
        tree = ast.parse(open(os.path.join(DIRECT_FIRE, "gen_squadcalc_weapons.py"), encoding="utf-8").read())
        self.gen = {}
        for stmt in tree.body:
            if isinstance(stmt, ast.Assign) and isinstance(stmt.targets[0], ast.Name) and stmt.targets[0].id in ("GAME_EXPLOSION", "SQUADCALC_ONLY", "RENAMED"):
                self.gen[stmt.targets[0].id] = ast.literal_eval(stmt.value)
        self.curves = {}
        for path in gamecheck.MOA_CURVES:
            asset = os.path.join(dump_dir, "SquadGame", "Content", path[len("/Game/"):-len(".0")] + ".uasset.json") if dump_dir else ""
            self.curves[path] = self.read_curve(asset)
        self.movement_keys = set()
        for entry in self.resolved.values():
            self.movement_keys |= set(((entry.get("projectile") or {}).get("movement") or {}))
        with open(MOUNT_LIMITS, encoding="utf-8") as source:
            mounts = json.load(source)
        # SquadCalc weapon -> its mount in the game, and the same by the name of its Squad Ballistics entry
        self.sc_mounts = {w["name"]: (mounts[w["name"]], w) for w in self.sc if w["name"] in mounts}
        renamed = self.gen["RENAMED"]
        self.sb_mounts = {renamed.get(w["ballistics"], w["ballistics"]): (mount, w) for mount, w in self.sc_mounts.values() if w.get("ballistics")}

    @staticmethod
    def read_curve(asset):
        """(value at 0, value at the last key) of a CurveFloat asset of the dump, None when the dump lacks it."""
        if not os.path.exists(asset):
            return None
        for export in json.load(open(asset)):
            keys = (((export.get("Properties") or {}).get("FloatCurve") or {}).get("Keys"))
            if keys:
                return keys[0]["Value"], keys[-1]["Value"]
        return None

    def blueprint(self, short):
        """The resolved entry of a Blueprint named by its file name, None when it is not exactly one."""
        found = self.by_base.get(short, [])
        return self.resolved[found[0]] if len(found) == 1 else None

    def target_classes(self, name):
        """The resolved entries of the classes of a gamecheck.py TARGETS group (the first is the reference)."""
        return [self.resolved.get(c.replace("Game/", "", 1)) or self.blueprint(c.rsplit("/", 1)[-1]) for c in gamecheck.TARGETS[name]]


def snap_effective(entry):
    """The model values of a snapshot entry, as gamecheck.effective() computes them from a resolved weapon."""
    v0, acc, timeout, cap = entry["velocity"], entry["acceleration"], entry["acceleration_timeout"], entry["max_speed"]
    boost = timeout if timeout > 0 else math.inf
    if timeout <= 0 and acc > 0 and cap:
        boost = max(0.0, (cap - v0) / acc)
    gravity = 0.0 if entry["ignore_gravity_while_boosting"] and acc and timeout == 0 else entry["gravity_scale"]
    if boost <= 0 or not acc:
        acc, boost = 0.0, 0.0
    return {"velocity": v0, "gravity": gravity, "acceleration": acc, "acceleration_time": None if math.isinf(boost) else boost,
            "max_speed": cap, "rotation_follows_velocity": entry["rotation_follows_velocity"] if acc else None,
            "lifespan_s": entry.get("lifespan") or None}


class Rows:
    """The rows of the long table, in the order they are added."""

    def __init__(self):
        self.rows = []

    def add(self, app, weapon, shell, name, used, game, source, label, same=True):
        assert name in INPUTS and (label in LABELS or label == "n/a"), (name, label)
        known = KNOWN.get((app, weapon, name))
        if known and not same:
            source = f"KNOWN: {known}. {source}"
        self.rows.append({"app": app, "weapon": weapon, "shell": shell, "input": name, "used": used, "game": game,
                          "source": source, "label": label, "same": same or bool(known)})


def weapon_class(data, cur, shell_name, shell_index, shell_count, snapshot_only=False):
    """(resolved entry or None, weapon path, projectile path) of one shell of an app weapon.

    A weapon Squad Ballistics has takes its reference class from the snapshot (``sources.weapon``); a Blueprint
    ``resolved.json`` lacks gives no entry (the values then come from the snapshot alone). For a shell of SquadCalc
    the class is the one the generator tables name for the shell (GAME_EXPLOSION, SQUADCALC_ONLY), else the class of
    the same index in gamecheck.py TARGETS when there are as many classes as shells, else the reference. A weapon only
    SquadCalc has takes its classes from SQUADCALC_ONLY and TARGETS.
    """
    snap = data.snap.get(cur) if cur else None
    if snap is not None:
        reference = data.resolved.get(snap["sources"]["weapon"])
        if reference is None:
            return None, "/Game/" + snap["sources"]["weapon"], "/Game/" + snap["sources"]["projectile"]
        if not snapshot_only:
            named = shell_blueprint(data, cur, shell_name)
            if named is None and cur in gamecheck.TARGETS and shell_count > 1 and len(gamecheck.TARGETS[cur]) == shell_count:
                named = data.target_classes(cur)[shell_index]
            if named is not None:
                return named, named["chain"][-1], named["projectile"]["chain"][-1]
        return reference, reference["chain"][-1], reference["projectile"]["chain"][-1]
    if cur in gamecheck.TARGETS:
        named = shell_blueprint(data, cur, shell_name)
        classes = data.target_classes(cur)
        if named is None:
            named = classes[shell_index] if len(classes) == shell_count else classes[0]
        if named is not None:
            return named, named["chain"][-1], named["projectile"]["chain"][-1]
    return None, None, None


def shell_blueprint(data, cur, shell_name):
    """The Blueprint a generator table names for the shell `shell_name` of the weapon `cur`, None when it names none."""
    for table in ("GAME_EXPLOSION", "SQUADCALC_ONLY"):
        rows = data.gen[table].get(cur) or []
        row = rows[0] if len(rows) == 1 else next((r for r in rows if r[0] == shell_name), None)
        if row is not None:
            found = data.blueprint(row[1])
            if found is not None:
                return found
    return None


def short(path):
    """The name at the end of a path."""
    return path.rsplit("/", 1)[-1] if path else "-"


def mount_limits(mount):
    """(game cell, source text) of the elevation limits a mount of mount_limits.json gives: its pitch range plus what the sight adds.

    The file names the Blueprint, widget, bone or component each number was read from.
    """
    pitch, reading = mount["pitch"], mount["reading"]
    return (f"{num(reading[0])}..{num(reading[1])}",
            f"mount pitch {num(pitch[0])}..{num(pitch[1])} ({short(mount['mount'])}) + {num(mount['sight_offset'])} the sight adds: tools/game_audit/data/mount_limits.json")


def mount_stop(mount, weapon):
    """Source text of a minimum distance: the barrel elevation the mount of a SquadCalc weapon stops at on the near side.

    A weapon fired on the high arc is stopped at the top of its range, one fired on the low arc at the bottom; the
    barrel is the weapon's scale offset above what the gunner reads.
    """
    stop = mount["reading"][1 if weapon.get("angleType") == "high" else 0] + (weapon.get("angleOffset") or 0)
    return f"range on level ground at the mount's stop, barrel at {num(stop)} degrees: tools/game_audit (mount_limits.json, calculator.mjs, check_calculator.py)"


def flight_rows(data, rows, app, weapon, shell, used, game_eff, found, source, snap):
    """Velocity, gravity, motor, cap and rotation rows: used = dict of the app's values, game_eff = effective model."""
    movement = ((found or {}).get("projectile") or {}).get("movement") or {}

    ok = close(used["velocity"], game_eff["velocity"])
    rows.add(app, weapon, shell, "velocity", num(used["velocity"]), num(game_eff["velocity"]), source + " WeaponConfig.MuzzleVelocity", "VERIFIED", ok)
    gravity_default = found is not None and "ProjectileGravityScale" not in movement
    ok = close(used["gravity"], game_eff["gravity"])
    rows.add(app, weapon, shell, "gravity", num(used["gravity"]), num(game_eff["gravity"]),
             "projectile ProjectileGravityScale" + (" (native default 1.0)" if gravity_default else ""),
             "INFERRED" if gravity_default else "VERIFIED", ok)
    game_time = game_eff["acceleration_time"]
    ok = close(used["acceleration"], game_eff["acceleration"]) and (
        not game_eff["acceleration"] or (game_time is not None and close(used["acceleration_time"], game_time, 5e-3)))
    motor_set = "ConstantAcceleration" in movement
    rows.add(app, weapon, shell, "motor",
             f"{num(used['acceleration'])} m/s2 for {num(used['acceleration_time'])} s" if used["acceleration"] else "none",
             f"{num(game_eff['acceleration'])} m/s2 for {num(game_time) if game_time is not None else 'whole flight'} s" if game_eff["acceleration"] else "none",
             "projectile ConstantAcceleration, ConstantAccelerationTimeout, bIgnoreGravityDuringConstantAcceleration" + ("" if motor_set or found is None else " (native default: none)"),
             "VERIFIED" if motor_set or found is None else "INFERRED", ok)
    ok = close(used["max_speed"], game_eff["max_speed"])
    rows.add(app, weapon, shell, "max_speed", num(used["max_speed"]) if used["max_speed"] else "none",
             num(game_eff["max_speed"]) if game_eff["max_speed"] else "none",
             "projectile MaxSpeed" + ("" if "MaxSpeed" in movement or found is None else " (native default: none)"),
             "VERIFIED" if "MaxSpeed" in movement or found is None else "INFERRED", ok)
    if game_eff["rotation_follows_velocity"] is None:
        rows.add(app, weapon, shell, "follows", "n/a", "n/a", "no motor: the rotation does not matter", "n/a")
    else:
        ok = used["follows"] == game_eff["rotation_follows_velocity"]
        rows.add(app, weapon, shell, "follows", num(used["follows"]), num(game_eff["rotation_follows_velocity"]),
                 "projectile bRotationFollowsVelocity" + ("" if "bRotationFollowsVelocity" in movement or found is None else " (ASQProjectile constructor sets true)"),
                 "VERIFIED" if "bRotationFollowsVelocity" in movement or found is None else "INFERRED", ok)
    rows.add(app, weapon, shell, "drag", "none", "none (no drag field)", "no projectile movement component of resolved.json has a drag field; SB ballistics.py docstring (native code, #4)", "INFERRED")


def launch_used_sb(e):
    return tuple(e.get(k, 0.0) for k in ("launch_height", "muzzle_forward", "muzzle_up"))


def sb_rows(data, rows):
    """Rows of the Squad Ballistics weapons."""
    for name, e in data.sb.items():
        snap = data.snap[name]
        found, wpath, ppath = weapon_class(data, name, "default", 0, 1, snapshot_only=True)
        source = "/Game/" + snap["sources"]["weapon"] + (" " if found is not None else " [snapshot only: not in resolved.json] ")
        game_eff = gamecheck.effective(found) if found is not None else snap_effective(snap)
        used = {"velocity": e["velocity"], "gravity": e.get("gravity", 1.0), "acceleration": e.get("acceleration", 0.0),
                "acceleration_time": e.get("acceleration_time", 0.0), "max_speed": e.get("max_speed", 0.0),
                "follows": e.get("rotation_follows_velocity", True)}
        flight_rows(data, rows, "SB", name, "-", used, game_eff, found, source, snap)
        launch = snap.get("launch")
        used_launch = launch_used_sb(e)
        if launch:
            game_launch = tuple(launch[k] for k in ("launch_height", "muzzle_forward", "muzzle_up"))
            rows.add("SB", name, "-", "launch", "/".join(num(v) for v in used_launch), "/".join(num(v) for v in game_launch),
                     "tools/game_weapons.py launch: " + snap["sources"].get("launch", "")[:160], "VERIFIED",
                     all(abs(a - b) < 6e-5 for a, b in zip(used_launch, game_launch)))
        elif any(used_launch):
            label, text = ORIGIN[(name, "launch")]
            rows.add("SB", name, "-", "launch", "/".join(num(v) for v in used_launch), "0.347 (note #13)" if "AGS-17" in name else "-", text, label)
        else:
            rows.add("SB", name, "-", "launch", "none (shot starts at the pivot on the ground)", "-", "handheld or unmodelled mount: no launch point in the files read by game_weapons.py", "ASSUMED")
        rows.add("SB", name, "-", "spread", "n/a", "n/a", "SB does not use the spread", "n/a")
        life = e.get("lifespan", 0.0)
        rows.add("SB", name, "-", "lifespan", num(life) if life else "none", num(snap.get("lifespan", 0)) if snap.get("lifespan") else "none",
                 "projectile InitialLifeSpan (game_weapons.json lifespan)", "VERIFIED", close(life, snap.get("lifespan", 0)))
        if e.get("category") not in DIRECT_HIT_CATEGORIES:
            rows.add("SB", name, "-", "explosion", "n/a", "n/a", "the round is judged by where it lands (grenade, artillery): no warhead field", "n/a")
        else:
            has_explosion = found is None or bool((found.get("projectile") or {}).get("explosion"))
            outer_native = found is not None and has_explosion and "ExplosiveDamageOuterRadius" in gamecheck.blast(found)["native"]
            label = "ASSUMED" if outer_native else "VERIFIED" if has_explosion else "INFERRED"
            rows.add("SB", name, "-", "explosion", e.get("warhead", "direct"), snap["warhead"],
                     (f"widest damaging explosion radius {num(snap['burst_radius'])} m of the projectile (game_weapons.py burst_radius)" if has_explosion
                      else "the projectile Blueprint chain sets no Explosive* field: it hits with its impact damage")
                     + (", outer radius is the native default 15 m" if outer_native else ""),
                     label, e.get("warhead", "direct") == snap["warhead"])
        for field in ("bore", "zoom"):
            game_value = snap[field]
            used_value = e.get(field, 0.0 if field == "bore" else 1.0)
            if game_value is None:
                rows.add("SB", name, "-", field, "none", "none", "aimed by elevation: no bore or zoom", "n/a")
