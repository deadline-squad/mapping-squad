def variants(data):
    """Rows (group, class, fields) of the classes of a gamecheck.py TARGETS group that differ from the group's first class."""
    out = []
    for name in gamecheck.TARGETS:
        classes = data.target_classes(name)
        if len(classes) < 2 or classes[0] is None:
            continue
        reference = classes[0]

        def fingerprint(entry):
            effective = gamecheck.effective(entry)
            try:
                blast = gamecheck.blast(entry)
                explosion = (blast["explosionDamage"], tuple(blast["explosionRadius"]), blast["explosionDistanceFromImpact"], blast["damageFallOff"])
            except ValueError:  # smoke: no explosion deals damage
                explosion = None
            return {"velocity": effective["velocity"], "gravity": effective["gravity"], "acceleration": effective["acceleration"],
                    "max_speed": effective["max_speed"], "lifespan": effective["lifespan_s"], "moa": effective["moa"],
                    "explosion": explosion}

        base = fingerprint(reference)
        for entry in classes[1:]:
            if entry is None:
                continue
            other = fingerprint(entry)
            show = lambda v: v if isinstance(v, tuple) or v is None else num(v)
            diff = [f"{k} {show(base[k])} -> {show(other[k])}" for k in base if base[k] != other[k]]
            if diff:
                out.append((name, short(entry["chain"][-1]), "; ".join(diff)))
    return out


def blame(sc_dir):
    """{weapon: (fields last written by the upstream author, fields last written by the fork)} for HAND_KEPT, from git blame of weapons.js."""
    try:
        text = subprocess.run(["git", "-C", sc_dir, "blame", "--line-porcelain", "-w", "--", "src/data/weapons.js"], check=True, capture_output=True, text=True).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    name, author, result = None, None, collections.defaultdict(lambda: collections.defaultdict(set))
    fields = ("velocity", "moa", "minDistance", "explosionDamage", "explosionRadius", "explosionDistanceFromImpact", "damageFallOff", "heightOffset",
              "angleOffset", "minElevation", "gravityScale", "projectileLifespan", "muzzle", "maxSpeed", "elevationRate", "holdElevation")
    for line in text.split("\n"):
        if line.startswith("author "):
            author = "upstream" if line[7:].strip().lower() in ("sh4rkman", "sharkman") else "fork"
        elif line.startswith("\t"):
            code = line[1:]
            match = re.match(r'        name: "([^"]+)"', code)
            if match:
                name = match.group(1)
            field = re.match(r"\s+(\w+):", code)
            if name in HAND_KEPT and field and field.group(1) in fields:
                result[name][field.group(1)].add(author)
    return {n: (sorted(f for f, a in result[n].items() if a == {"upstream"}), sorted(f for f, a in result[n].items() if "fork" in a)) for n in HAND_KEPT}


