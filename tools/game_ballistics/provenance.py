def tsv(rows):
    """The long table as TSV text."""
    head = ["app", "weapon", "shell", "input", "used", "game", "source", "label", "equal"]
    lines = ["\t".join(head)]
    for r in rows:
        if r["label"] == "n/a":
            continue
        lines.append("\t".join(str(r[k]).replace("\t", " ").replace("\n", " ") for k in ("app", "weapon", "shell", "input", "used", "game", "source", "label")) + "\t" + ("yes" if r["same"] else "NO"))
    return "\n".join(lines) + "\n"


def class_table(data, rows, lang):
    """The classes of the game with the weapons that use them."""
    t = TEXT[lang]
    members = collections.OrderedDict()

    def add(key, app, name):
        members.setdefault(key, {"SB": [], "SC": []})
        if name not in members[key][app]:
            members[key][app].append(name)

    for name in data.sb:
        found, wpath, ppath = weapon_class(data, name, "default", 0, 1, snapshot_only=True)
        add((wpath, ppath), "SB", name)
    renamed = data.gen["RENAMED"]
    for w in data.sc:
        ballistics = w.get("ballistics")
        cur = renamed.get(ballistics, ballistics) if ballistics else HAND_TO_GAME.get(w["name"])
        if cur not in data.snap and cur not in gamecheck.TARGETS:
            continue
        for index, shell in enumerate(w["shells"]):
            found, wpath, ppath = weapon_class(data, cur, shell["name"], index, len(w["shells"]))
            if wpath:
                add((wpath, ppath), "SC", w["name"])
    lines = [f"| # | {t['gameclass']} | v m/s | g | {t['motor']} | cap | {t['lifespan']} s | MOA | {t['explosion']} | SB | SC |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for number, (key, who) in enumerate(members.items(), 1):
        wpath, ppath = key
        found = data.resolved.get(wpath.replace("/Game/", "", 1))
        if found is not None:
            effective = gamecheck.effective(found)
            blast = gamecheck.blast(found)
            curve = (found["config"].get("MOACurve") or {}).get("ObjectPath")
            moa = f"{num(blast['moa'])} (curve {short(curve)})" if curve else num(blast["moa"])
            motor = f"{num(effective['acceleration'])} x {num(effective['acceleration_time']) if effective['acceleration_time'] is not None else 'all'} s" if effective["acceleration"] else "-"
            if (found.get("projectile") or {}).get("explosion"):
                explosion = f"{num(blast['explosionDamage'])}, {num(blast['explosionRadius'][0])}-{num(blast['explosionRadius'][1])}, {num(blast['explosionDistanceFromImpact'])}, x{num(blast['damageFallOff'])}"
                if blast["native"]:
                    explosion += " [native: " + ", ".join(n.replace("Explosive", "").replace("DamageFalloff", "falloff").replace("DamageOuterRadius", "outer").replace("DamageInnerRadius", "inner").replace("DamageDistanceFromImpactNormal", "height") for n in blast["native"]) + "]"
            else:
                explosion = "none"
            cells = [num(effective["velocity"]), num(effective["gravity"]), motor, num(effective["max_speed"]) if effective["max_speed"] else "-",
                     num(effective["lifespan_s"]) if effective["lifespan_s"] else "-", moa, explosion]
        else:
            snap = next(data.snap[n] for n in who["SB"] if n in data.snap) if who["SB"] else None
            effective = snap_effective(snap)
            motor = f"{num(effective['acceleration'])} x {num(effective['acceleration_time']) if effective['acceleration_time'] is not None else 'all'} s" if effective["acceleration"] else "-"
            cells = [num(effective["velocity"]), num(effective["gravity"]), motor, num(effective["max_speed"]) if effective["max_speed"] else "-",
                     num(snap.get("lifespan", 0)) if snap.get("lifespan") else "-", "not in resolved.json", f"radius {num(snap['burst_radius'])} (snapshot)"]
        path = f"`{wpath.replace('/Game/', '')}` -> `{short(ppath)}`"
        lines.append(f"| C{number:02d} | {path} | " + " | ".join(cells) + f" | {'; '.join(who['SB']) or '-'} | {'; '.join(who['SC']) or '-'} |")
    return "\n".join(lines), {key: f"C{n:02d}" for n, key in enumerate(members, 1)}


def origin_groups(rows, lang):
    """Inputs the game files do not decide (or no committed tool reads): grouped by input, label and source text."""
    t = TEXT[lang]
    groups = collections.OrderedDict()
    for r in rows:
        if r["label"] in ("n/a",) or r["input"] in ("velocity", "gravity", "motor", "max_speed", "follows", "drag"):
            continue
        if r["label"] == "VERIFIED" or (r["label"] == "INFERRED" and r["input"] in ("explosion", "limits")) and False:
            continue
        key = (r["input"], r["label"], re.sub(r"via SB entry [^:]*:?", "via SB entry:", r["source"])[:170])
        groups.setdefault(key, set()).add(f"{r['app']} {r['weapon']}")
    out = [f"| {t['input']} | {t['label']} | {t['source']} | n | {t['weapons']} |", "|---|---|---|---|---|"]
    order = {name: i for i, name in enumerate(INPUTS)}
    for (name, label, source), who in sorted(groups.items(), key=lambda kv: (order[kv[0][0]], LABELS.index(kv[0][1]), kv[0][2])):
        if label == "VERIFIED":
            continue
        names = sorted(who)
        shown = "; ".join(names) if len(names) <= 14 else "; ".join(names[:14]) + f"; ... (+{len(names) - 14})"
        out.append(f"| {t['inputs'][name]} | {label} | {source.replace('|', '/')} | {len(names)} | {shown} |")
    return "\n".join(out)


def counts_table(rows, lang):
    """Rows per input and label, per app."""
    t = TEXT[lang]
    counter = collections.Counter((r["app"], r["input"], r["label"]) for r in rows if r["label"] != "n/a")
    lines = [f"| {t['input']} | " + " | ".join(f"{app} {label}" for app in ("SB", "SC") for label in LABELS) + " |", "|---|" + "---|" * 8]
    totals = collections.Counter()
    for name in INPUTS:
        cells = []
        for app in ("SB", "SC"):
            for label in LABELS:
                n = counter[(app, name, label)]
                totals[(app, label)] += n
                cells.append(str(n) if n else "-")
        lines.append(f"| {t['inputs'][name]} | " + " | ".join(cells) + " |")
    lines.append("| **total** | " + " | ".join(f"**{totals[(app, label)]}**" for app in ("SB", "SC") for label in LABELS) + " |")
    return "\n".join(lines)


def index_table(data, classes, lang):
    """Every weapon of both apps with its classes and where its values come from."""
    t = TEXT[lang]
    lines = [f"| {t['app']} | {t['weapon']} | {t['classes']} | {t['origin']} |", "|---|---|---|---|"]
    renamed = data.gen["RENAMED"]
    for name, e in data.sb.items():
        found, wpath, ppath = weapon_class(data, name, "default", 0, 1, snapshot_only=True)
        origin = t["game"]
        if e.get("hold_rate"):
            origin += "; hold model fitted (67 measurements)"
        if (name, "launch") in ORIGIN:
            origin += "; launch hand-read"
        if name in data.sb_mounts and data.snap[name]["elevation_limits"] is None:
            origin += "; limits from the mount's pitch (tools/game_audit)"
        lines.append(f"| SB | {name} | {classes.get((wpath, ppath), '-')} | {origin} |")
    for w in data.sc:
        name = w["name"]
        ballistics = w.get("ballistics")
        cur = renamed.get(ballistics, ballistics) if ballistics else HAND_TO_GAME.get(name)
        kind = sc_kind(w)
        ids = []
        if cur in data.snap or cur in gamecheck.TARGETS:
            for index, shell in enumerate(w["shells"]):
                _, wpath, ppath = weapon_class(data, cur, shell["name"], index, len(w["shells"]))
                ids.append(classes.get((wpath, ppath), "-"))
        if kind == "mod":
            origin = t["mod"]
        elif kind == "generated":
            origin = t["generated"] if cur in data.sb else t["autocannon"]
        else:
            origin = t["hand"]
            if name == "AGS-17":
                origin += "; hold model fitted (67 measurements)"
            elif name == "Mk19":
                origin += "; height, angle offset, limits, min distance from upstream"
            elif name == "BTR4-AGS":
                origin += "; height and angle offset from upstream, limits from the mount's pitch (tools/game_audit)"
        lines.append(f"| SC | {name} | {', '.join(dict.fromkeys(ids)) or '-'} | {origin} |")
    return "\n".join(lines)


def variants_table(data, lang):
    """The variants block."""
    t = TEXT[lang]
    lines = [f"| {t['weapon']} | {t['variant']} | {t['differs']} |", "|---|---|---|"]
    for group, cls, diff in variants(data):
        lines.append(f"| {group} | {cls} | {diff.replace('|', '/')} |")
    return "\n".join(lines)


def origin_table(blamed, lang):
    """Fields of the hand-kept SC weapons by the author of their last change."""
    t = TEXT[lang]
    if blamed is None:
        return "git blame is not available for the SquadCalc checkout."
    lines = [f"| {t['weapon']} | {t['upstream']} | {t['fork']} |", "|---|---|---|"]
    for name in HAND_KEPT:
        up, fork = blamed[name]
        lines.append(f"| {name} | {', '.join(up) or '-'} | {', '.join(fork) or '-'} |")
    return "\n".join(lines)


def generate(data, lang):
    """{block name: text} for one language and the long table."""
    rows = all_rows(data)
    class_text, classes = class_table(data, rows, lang)
    return rows, {
        "classes": class_text,
        "origins": origin_groups(rows, lang),
        "counts": counts_table(rows, lang),
        "index": index_table(data, classes, lang),
        "variants": variants_table(data, lang),
        "blame": origin_table(blame(data.sc_dir), lang),
    }


def unexplained(rows):
    """Rows whose app value differs from the game and that no documented deviation explains."""
    return [r for r in rows if not r["same"]]


BLOCK = "<!-- generated:{name} -->\n{text}\n<!-- /generated:{name} -->"
BLOCK_RE = re.compile(r"<!-- generated:(\w+) -->\n(.*?)\n?<!-- /generated:\1 -->", re.S)


def write_docs(directory, data):
    """Rewrite the generated blocks of both documents and the TSV."""
    for lang, suffix in (("en", ""), ("ru", ".ru")):
        path = os.path.join(directory, f"data-provenance{suffix}.md")
        text = open(path, encoding="utf-8").read()
        rows, blocks = generate(data, lang)
        text = BLOCK_RE.sub(lambda m: BLOCK.format(name=m.group(1), text=blocks[m.group(1)]), text)
        open(path, "w", encoding="utf-8").write(text)
    open(os.path.join(directory, "data-provenance.tsv"), "w", encoding="utf-8").write(tsv(rows))
    return rows


def missing_from_index(index, names):
    """The problems of a weapon index (text of the generated block) that lacks some of `names`, a list of (app, name)."""
    return [f"{app} weapon '{name}' is not in the index" for app, name in names if f"| {app} | {name} |" not in index]


def check_docs(directory, data):
    """List of problems: a weapon missing from a document, a stale block, an unexplained difference."""
    problems = []
    rows = all_rows(data)
    names = [("SB", n) for n in data.sb] + [("SC", w["name"]) for w in data.sc]
    for lang, suffix in (("en", ""), ("ru", ".ru")):
        path = os.path.join(directory, f"data-provenance{suffix}.md")
        if not os.path.exists(path):
            problems.append(f"{path}: missing")
            continue
        text = open(path, encoding="utf-8").read()
        found = dict(BLOCK_RE.findall(text))
        problems += [f"{os.path.basename(path)}: {problem}" for problem in missing_from_index(found.get("index", ""), names)]
        _, blocks = generate(data, lang)
        for block, expected in blocks.items():
            if block == "blame":
                continue
            if found.get(block) != expected:
                problems.append(f"{os.path.basename(path)}: block '{block}' is stale (run with --write)")
    tsv_path = os.path.join(directory, "data-provenance.tsv")
    if not os.path.exists(tsv_path) or open(tsv_path, encoding="utf-8").read() != tsv(rows):
        problems.append("data-provenance.tsv is stale (run with --write)")
    for r in unexplained(rows):
        problems.append(f"{r['app']} {r['weapon']} {r['shell']} {r['input']}: used {r['used']}, game {r['game']}")
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--resolved", required=True)
    parser.add_argument("--dump", default="")
    parser.add_argument("--sb", required=True, help="Squad Ballistics checkout")
    parser.add_argument("--sc", required=True, help="SquadCalc checkout")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", metavar="DOCS_DIR")
    action.add_argument("--check", metavar="DOCS_DIR")
    args = parser.parse_args(argv)
    data = Data(os.path.expanduser(args.resolved), os.path.expanduser(args.sb), os.path.expanduser(args.sc), os.path.expanduser(args.dump) if args.dump else "")
    if args.write:
        rows = write_docs(args.write, data)
        bad = unexplained(rows)
        print(f"{len(rows)} rows, {sum(1 for r in rows if r['label'] != 'n/a')} labelled, {len(bad)} differ from the game")
        for r in bad:
            print("DIFF", r["app"], r["weapon"], r["shell"], r["input"], r["used"], "|", r["game"])
        return 1 if bad else 0
    problems = check_docs(args.check, data)
    print("\n".join(problems) if problems else "documents, tables and game values agree")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
