"""Where every input of the firing solution comes from, per weapon, in Squad Ballistics (SB) and SquadCalc (SC).

Compares the weapon data of both apps with the game files and writes the tables of
``tools/volumetric/docs/data-provenance.md`` (and ``.ru.md``) and the long form
``data-provenance.tsv`` (one line per weapon, shell and input: value used, game value, source, label).

Usage (from the deployment repository)::

    python3 tools/game_ballistics/provenance.py --resolved ~/data/squad-weapons/resolved.json \\
        --dump ~/data/squad-weapons/dump --sb <Squad-Ballistics checkout> --sc <SquadCalc checkout> \\
        --write tools/volumetric/docs          # rewrite the generated blocks and the TSV
    python3 tools/game_ballistics/provenance.py ... --check tools/volumetric/docs
                                               # exit 1 when a weapon is missing from the documents, a generated
                                               # block is stale, or an app value differs from the game unexplained

Game values: ``resolved.json`` (``collect.py``: every weapon Blueprint with its WeaponConfig and projectile merged along
the Blueprint chain), ``gamecheck.py`` (effective flight model, explosion, spread curves) and Squad Ballistics'
``tests/data/game_weapons.json`` (the snapshot ``tools/game_weapons.py`` writes, which also holds the seven weapons whose
Blueprints ``resolved.json`` lacks). The elevation limits of the weapons the snapshot derives none for (mortar, UB-32,
Hell Cannon, BTR-4 AGS) and the stop every minimum distance is computed at come from
``tools/game_audit/data/mount_limits.json``: the pitch range of each mount and what its sight adds to it, read from the
game files by ``tools/game_audit/mounts.py``. Labels (the vocabulary of ``docs/thesis-methods-and-results.md`` section 0):

* VERIFIED   the value is read from the game files by a committed tool and the app's value equals it;
* INFERRED   derived from verified data by a stated argument (a native default, a curve's resting value, a limit
             computed from the mount's pitch);
* UNVERIFIED recorded without a reproducible output (a fit to the owner's measurements, a one-off read of a skeleton,
             a Blueprint the dump here lacks) or not decidable from the server files;
* ASSUMED    not in the server files at all (Workshop mods, handheld bore and zoom, native C++ explosion defaults,
             SquadCalc's default lifespan).
"""

