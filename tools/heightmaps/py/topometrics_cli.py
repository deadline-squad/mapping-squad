"""Write the per-map topographic summaries: python topometrics_cli.py HEIGHTMAPS_DIR OUT_DIR [map ...]

HEIGHTMAPS_DIR holds <map>/heightmap.webp + meta.json (the served heightmaps); OUT_DIR gets <map>.json and
README.md, the Markdown table of every JSON in OUT_DIR. Definitions of the metrics: topometrics.py.
"""

import json
import os
import sys
import time

import topometrics

TABLE_METRICS = (
    ("elevation_m", "Elevation, m", 1),
    ("slope_deg", "Slope, deg", 2),
    ("profile_curvature_per_m", "Profile curvature, 1/m", 5),
    ("plan_curvature_per_m", "Plan curvature, 1/m", 5),
    ("tpi_m", "TPI 3x3, m", 3),
    ("tpi_10m_m", "TPI 10 m, m", 3),
    ("tri_m", "TRI, m", 3),
    ("roughness_m", "Roughness, m", 3),
    ("svf", "Sky-view factor", 3),
    ("openness_deg", "Openness, deg", 2),
)


def write_markdown(out_dir):
    """README.md: a table per metric across the maps in out_dir, and the slope class shares."""
    summaries = []
    for name in sorted(os.listdir(out_dir)):
        if name.endswith(".json"):
            with open(os.path.join(out_dir, name)) as handle:
                summaries.append(json.load(handle))
    lines = [
        "# Topographic metrics per map",
        "",
        "Generated by `py/topometrics_cli.py` from the served heightmaps; per-cell values, float64 (sky-view factor and",
        "openness: RVT, float32). Definitions, sign conventions and window shapes: docstring of `py/topometrics.py`.",
        "Statistics are over the finite cells of the whole map; flat cells have no aspect or curvature.",
        "Belaya is terrain-only community data (SquadHeight 1.3.0, not derived from the server package; its surface",
        "includes what the SDK trace hits, rocks and buildings, unseparated): its rows are not comparable in accuracy.",
        "",
        "| Map | Cell, m | Cells | Slope over 15 deg | over 30 deg | over 45 deg | over 60 deg |",
        "|---|---|---|---|---|---|---|",
    ]
    for item in summaries:
        share = item["slope_share"]
        lines.append(f"| {item['map']} | {item['cell_m']} | {item['rows'] * item['cols']:,} | "
                     + " | ".join(f"{share[f'over_{limit}_deg'] * 100:.1f} %" for limit in (15, 30, 45, 60)) + " |")
    for key, title, digits in TABLE_METRICS:
        lines += ["", f"## {title}", "", "| Map | min | p1 | p5 | p25 | median | mean | p75 | p95 | p99 | max |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for item in summaries:
            stats = item["metrics"].get(key)
            if stats is None:
                continue
            values = (stats[k] for k in ("min", "p1", "p5", "p25", "p50", "mean", "p75", "p95", "p99", "max"))
            lines.append(f"| {item['map']} | " + " | ".join(f"{value:.{digits}f}" for value in values) + " |")
    with open(os.path.join(out_dir, "README.md"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


def main(argv):
    heightmaps, out_dir = argv[1], argv[2]
    maps = argv[3:] or sorted(name for name in os.listdir(heightmaps) if os.path.isdir(os.path.join(heightmaps, name)))
    os.makedirs(out_dir, exist_ok=True)
    for name in maps:
        started = time.time()
        z, meta = topometrics.load_heightmap(os.path.join(heightmaps, name))
        summary = topometrics.map_summary(z, meta)
        summary["seconds"] = round(time.time() - started, 1)
        with open(os.path.join(out_dir, f"{name}.json"), "w") as handle:
            json.dump(summary, handle, indent=1)
        print(f"{name} {z.shape} {summary['seconds']} s", flush=True)
    write_markdown(out_dir)


if __name__ == "__main__":
    main(sys.argv)
